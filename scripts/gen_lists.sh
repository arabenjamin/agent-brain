#!/usr/bin/env bash
# Write hbi-frontend/src/lib/lists.generated.ts from the bundles' closed lists
# (plugins/*/schemas/lists/*.json, CODEBASE_SPLIT_PLAN Phase 1), so the HBI
# takes claim statuses, note types, todo statuses and the rest from the same
# place the brain does. Each list becomes a const array and its type:
#   claim-statuses -> CLAIM_STATUSES, type ClaimStatus
#
# The list files are written by their owning crate's test; after changing a
# list in Rust run that test with SCHEMA_REGENERATE=1, then this script.
#
#   scripts/gen_lists.sh           write the file
#   scripts/gen_lists.sh --check   fail if the committed file is stale (CI)
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

out=hbi-frontend/src/lib/lists.generated.ts

render() {
  echo "// Generated by scripts/gen_lists.sh from plugins/*/schemas/lists/*.json."
  echo "// Do not edit: change the list in Rust, rerun its test with"
  echo "// SCHEMA_REGENERATE=1, then rerun scripts/gen_lists.sh."
  local f name const type
  for f in $(git ls-files --cached --others --exclude-standard -- ':(glob)plugins/*/schemas/lists/*.json' | sort); do
    name=$(jq -r .name "$f")
    const=$(echo "$name" | tr 'a-z-' 'A-Z_')
    # Singular, PascalCase: statuses -> Status, kinds -> Kind.
    type=$(echo "$name" | sed -E 's/uses$/us/; t; s/s$//' | awk -F- '{ for (i = 1; i <= NF; i++) printf "%s", toupper(substr($i, 1, 1)) substr($i, 2) }')
    echo
    echo "/** $(jq -r .description "$f") ($f) */"
    echo "export const $const = $(jq -c .values "$f" | sed 's/,/, /g') as const;"
    echo "export type $type = (typeof $const)[number];"
  done
}

if [[ "${1:-}" == "--check" ]]; then
  if ! diff -u "$out" <(render) >&2; then
    echo "$out is stale: run scripts/gen_lists.sh and commit it." >&2
    exit 1
  fi
  exit 0
fi

render > "$out.new"
mv "$out.new" "$out"
echo "wrote $out"
